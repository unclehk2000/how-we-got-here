def build():
    out = {}
    for name, T in [('NQ', NQ), ('ES', ES), ('RTY', RTY)]:
        P = pd.DataFrame(T, index=range(1, 14)).T.sort_index(); P.columns = list(range(1, 13)) + ['yr']
